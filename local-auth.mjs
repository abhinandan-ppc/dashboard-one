// local-auth.mjs — serve this repo on localhost WITH live sheet data.
//
// In production the sheet proxies run as Vercel Edge Functions
// (api/ebtp-proxy, api/balance-heat-proxy, api/zstk-proxy, api/autobtr-proxy), authenticated by the
// SHEETS_SA_* env vars. On localhost neither half exists: static hosting has
// no /api layer, and the credential lives in the gitignored key file
// service-account.json instead of an env var. This file bridges both gaps
// with zero dependencies:
//
//   node local-auth.mjs          → http://127.0.0.1:3000  (default port;
//       override with --port N or PORT=… — browse the dashboards through
//       THIS url so the pages' relative fetch('/api/…') reaches this server)
//     • loads service-account.json for the other dashboard proxies and mounts
//       the truck dashboard's Google Drive database routes on the same origin;
//     • serves the static dashboards from the repo root on the SAME origin,
//       so every page's relative fetch('/api/…') resolves without changes;
//     • needs no login: index.html already detects localhost (isLocalDev)
//       and skips the auth gate there.
//
//   node local-auth.mjs --env    → writes .env.local (gitignored) with the
//     SHEETS_SA_* pair lifted from service-account.json, for anyone who
//     prefers `vercel dev` over this server.
//
// Spreadsheet proxy credentials are loaded from root .env.local or the
// truck-dashboard app's .env.local. The service-account key below is used only
// for the other dashboards' sheet proxies.

import { createServer } from 'node:http';
import { readFile, writeFile, stat } from 'node:fs/promises';
import { createReadStream } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parseEnvText } from './local-auth-env.mjs';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SA_PATH = path.join(ROOT, 'service-account.json');
const argv = process.argv.slice(2);

async function loadEnvFile(file) {
  try {
    const values = parseEnvText(await readFile(file, 'utf8'), process.env);
    Object.assign(process.env, values);
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
}

await loadEnvFile(path.join(ROOT, '.env.local'));
// The standalone truck dashboard keeps its Drive credentials in its own Vite
// app folder. Load them as a fallback; root .env.local / shell vars take priority.
await loadEnvFile(path.join(ROOT, 'truck-dashboard', '.env.local'));

async function loadServiceAccount() {
  let raw;
  try {
    raw = await readFile(SA_PATH, 'utf8');
  } catch {
    console.error(`local-auth: ${SA_PATH} not found.`);
    console.error('  The key file is local-only (gitignored). Copy the service-account JSON');
    console.error('  exported from GCP to the repo root — see SVA.md, "The service account" —');
    console.error('  then re-run. (For `vercel dev` instead: node local-auth.mjs --env)');
    process.exit(1);
  }
  let sa;
  try {
    sa = JSON.parse(raw);
  } catch (e) {
    console.error(`local-auth: service-account.json is not valid JSON (${e.message})`);
    process.exit(1);
  }
  if (!sa.client_email || !sa.private_key) {
    console.error('local-auth: service-account.json is missing client_email / private_key.');
    process.exit(1);
  }
  return sa;
}

// ── `--env` mode: emit .env.local for `vercel dev`, then stop ──────────────
if (argv.includes('--env')) {
  const sa = await loadServiceAccount();
  const body = [
    '# Generated by `node local-auth.mjs --env` — local sheet auth for vercel dev.',
    '# Same credential pair production sets by hand in Vercel (see SVA.md).',
    '# api/_sheets-sa.js unescapes \\n in the key itself, so \\n-escaped PEM is fine.',
    `SHEETS_SA_CLIENT_EMAIL=${JSON.stringify(sa.client_email)}`,
    `SHEETS_SA_PRIVATE_KEY=${JSON.stringify(sa.private_key)}`,
    '',
  ].join('\n');
  const out = path.join(ROOT, '.env.local');
  await writeFile(out, body, 'utf8');
  console.log(`local-auth: wrote ${out}`);
  console.log(`  SHEETS_SA_CLIENT_EMAIL=${sa.client_email}`);
  process.exit(0);
}

// ── Auth: inject the env pair BEFORE any handler asks Google for a token ───
// api/_sheets-sa.js reads process.env at token time, so setting it here is
// all the wiring the production code needs to run unmodified under Node.
const sa = await loadServiceAccount();
process.env.SHEETS_SA_CLIENT_EMAIL = sa.client_email;
process.env.SHEETS_SA_PRIVATE_KEY = sa.private_key;
if (process.env.DRIVE_SCRIPT_URL && process.env.DRIVE_SCRIPT_SECRET) {
  console.log('local-auth: Google Drive database credentials loaded.');
} else {
  console.warn('local-auth: Google Drive data is not configured; set DRIVE_SCRIPT_URL and DRIVE_SCRIPT_SECRET in .env.local.');
}

// ── The same Edge handlers Vercel runs — imported, not re-implemented ──────
const API_ROUTES = {
  '/api/ebtp-proxy': new URL('./api/ebtp-proxy.js', import.meta.url),
  '/api/balance-heat-proxy': new URL('./api/balance-heat-proxy.js', import.meta.url),
  '/api/zstk-proxy': new URL('./api/zstk-proxy.js', import.meta.url),
  '/api/autobtr-proxy': new URL('./api/autobtr-proxy.js', import.meta.url),
  '/api/truckdb-proxy': new URL('./api/truckdb-proxy.js', import.meta.url),
};

// Truck dashboard's source tree is a separate Vite app. Mount its Drive database
// API in the root local server too, so both the ported static page and the React
// app can fetch the same Drive XLSX/native Google Sheets on localhost:3000.
const TRUCK_DB_ROUTES = new Set(['/api/database', '/api/database/file']);
const { handleDatabase } = await import('./truck-dashboard/tools/drive.mjs');

const handlerCache = new Map();
async function getHandler(pathname) {
  if (!handlerCache.has(pathname)) {
    handlerCache.set(pathname, (await import(API_ROUTES[pathname])).default);
  }
  return handlerCache.get(pathname);
}

// ── Static files, served from the repo root on the same origin as /api ─────
const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.htm': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
  '.csv': 'text/csv; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.md': 'text/plain; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
  '.webp': 'image/webp',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.webmanifest': 'application/manifest+json',
  '.pdf': 'application/pdf',
  '.xlsx': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
};

function send(res, status, headers, body) {
  if (!res.headersSent) res.writeHead(status, headers);
  res.end(body);
}

// Edge handlers are `(request?) => Response`; pass query parameters through so
// routes that select a file (including the truck database) receive the right kind.
// The body is copied verbatim; this local-only server is bound to 127.0.0.1.
async function serveApi(url, res) {
  const handler = await getHandler(url.pathname);
  const requestUrl = `http://127.0.0.1${url.pathname}${url.search}`;
  const upstream = await handler(new Request(requestUrl));
  const headers = {};
  upstream.headers.forEach((v, k) => { headers[k] = v; });
  headers['Access-Control-Allow-Origin'] = '*';
  const buf = Buffer.from(await upstream.arrayBuffer());
  send(res, upstream.status, headers, buf);
}

async function serveStatic(pathname, res) {
  let rel;
  try {
    rel = decodeURIComponent(pathname);
  } catch {
    return send(res, 400, { 'Content-Type': 'text/plain' }, 'Bad request');
  }
  if (rel === '/') rel = '/index.html';
  const file = path.normalize(path.join(ROOT, rel));
  // Traversal guard: never serve anything above the repo root.
  if (!file.startsWith(ROOT + path.sep)) {
    return send(res, 403, { 'Content-Type': 'text/plain' }, 'Forbidden');
  }
  try {
    const info = await stat(file);
    if (!info.isFile()) return send(res, 404, { 'Content-Type': 'text/plain' }, 'Not found');
    const type = MIME[path.extname(file).toLowerCase()] || 'application/octet-stream';
    res.writeHead(200, {
      'Content-Type': type,
      'Cache-Control': 'no-cache', // always re-read edits while developing
      'Content-Length': info.size,
    });
    const stream = createReadStream(file);
    stream.on('error', () => res.destroy());
    stream.pipe(res);
  } catch {
    send(res, 404, { 'Content-Type': 'text/plain' }, 'Not found');
  }
}

const server = createServer(async (req, res) => {
  try {
    const url = new URL(req.url, 'http://localhost');
    const { pathname } = url;
    if (req.method === 'OPTIONS') {
      return send(res, 204, {
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'GET, HEAD, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type, Authorization',
      });
    }
    // Check Vercel-style routes before static serving. On VS Code Live Preview
    // these paths are shadowed by physical files under /api, so route API calls
    // through this server while it runs on port 3000.
    const databasePath = pathname.replace(/\/+$/, '');
    if (databasePath === '/api/database' || databasePath === '/api/database/file') {
      url.pathname = databasePath;
      if (databasePath === '/api/database' && url.searchParams.has('name')) url.pathname = '/api/database/file';
      if (url.pathname === '/api/database' && url.searchParams.has('file')) url.pathname = '/api/database/file';
      if (url.pathname === '/api/database/file' && !url.searchParams.has('name') && url.searchParams.has('file')) {
        url.searchParams.set('name', url.searchParams.get('file'));
      }
      if (url.pathname === '/api/database/file' && !url.searchParams.has('name') && url.searchParams.has('id')) {
        url.searchParams.set('name', url.searchParams.get('id'));
      }
      if (url.searchParams.has('name') && url.searchParams.get('name').includes('/')) {
        url.searchParams.set('name', url.searchParams.get('name').split('/').pop());
      }
      if (req.method !== 'GET' && req.method !== 'HEAD') return send(res, 405, { 'Content-Type': 'text/plain' }, 'Method not allowed');
      const result = await handleDatabase(url, process.env);
      if (!result) return send(res, 404, { 'Content-Type': 'application/json; charset=utf-8' }, JSON.stringify({ error: 'Not found', pathname }));
      const headers = {};
      result.headers.forEach((v, k) => { headers[k] = v; });
      headers['Access-Control-Allow-Origin'] = '*';
      const body = req.method === 'HEAD' ? null : Buffer.from(await result.arrayBuffer());
      return send(res, result.status, headers, body);
    }
    if (pathname in API_ROUTES) return await serveApi(url, res);

    if (pathname.startsWith('/api/')) {
      return send(res, 404, {
        'Content-Type': 'application/json; charset=utf-8',
        'Access-Control-Allow-Origin': '*',
      }, JSON.stringify({
        error: `No local handler for ${pathname} — local-auth.mjs only mounts the configured sheet proxies.`,
      }));
    }
    if (req.method !== 'GET' && req.method !== 'HEAD') {
      return send(res, 405, { 'Content-Type': 'text/plain' }, 'Method not allowed');
    }
    return await serveStatic(pathname, res);
  } catch (e) {
    console.error(`local-auth: ${req.method} ${req.url} failed —`, e.stack || e);
    send(res, 500, { 'Content-Type': 'text/plain' }, 'local-auth: internal error (see terminal)');
  }
});

const portFlag = argv.indexOf('--port');
const port = (portFlag !== -1 && Number(argv[portFlag + 1])) || Number(process.env.PORT) || 3000;

server.on('error', (err) => {
  if (err && err.code === 'EADDRINUSE') {
    console.error(`local-auth: port ${port} is already in use.`);
    console.error('  Stop whatever is listening there, or pick another port:');
    console.error(`    node local-auth.mjs --port ${port + 1}`);
    console.error('  Then browse the dashboards through THAT url — the pages call');
    console.error("  fetch('/api/…') on their own origin, so the server hosting them");
    console.error('  must also be this one.');
    process.exit(1);
  }
  throw err;
});

server.listen(port, '127.0.0.1', () => {
  console.log('local-auth: service account →', sa.client_email);
  console.log(`local-auth: dashboards      → http://127.0.0.1:${port}/`);
  console.log('local-auth: sheet proxies   → /api/ebtp-proxy  /api/balance-heat-proxy  /api/zstk-proxy  /api/autobtr-proxy');
  console.log('local-auth: truck database  → /api/database  /api/database/file (configure DRIVE_SCRIPT_URL and DRIVE_SCRIPT_SECRET)');
  console.log('local-auth: Ctrl+C to stop');
});
