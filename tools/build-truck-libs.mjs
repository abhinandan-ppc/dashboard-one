// One-shot build: concatenates the truck app's pure logic libs into a single
// classic script (truck-dashboard-libs.js) for the static Truck-Dashboard page.
// Transforms per file:
//   - `import ... from './x'` lines are dropped (order below handles deps)
//   - `import * as XLSX from 'xlsx'` -> const XLSX = window.XLSX (CDN global)
//   - `export` keywords stripped (names go on a namespace at the end)
//   - engine.js's `window.INDIA_CITY_FOREIGN_KEYS` fallback relies on cities.js
//     having run first — that is the load order here too.
// Run: node tools/build-truck-libs.mjs   (rerun after editing truck-dashboard/src)
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'truck-dashboard/src';
const XLSX_LINE = "var XLSX = window.XLSX; // SheetJS loaded from CDN in Truck-Dashboard.html";

function transform(name) {
  let code = readFileSync(`${SRC}/lib/${name}`, 'utf8');
  code = code.replace(/^import \* as XLSX from 'xlsx';\s*$/m, XLSX_LINE);
  code = code.replace(/^import .*?;\s*$/gm, '');
  code = code.replace(/^import\s*\{[\s\S]*?\}\s*from\s*['"].*?['"];\s*$/gm, '');
  code = code.replace(/^\s*export\s+(?=(const|let|var|function|async function))/gm, '');
  code = code.replace(/^\s*export\s*\{[\s\S]*?\};?\s*$/gm, '');
  return `/* ── ${name} (ported from ${SRC}/lib/${name}) ─────────────────────────── */\n` + code.trim() + '\n';
}

// Dependency order: cities first (engine imports its data), then lc (engine imports it).
const out = [
  '// Auto-generated by tools/build-truck-libs.mjs — DO NOT hand-edit.\n'
  + '// Edit truck-dashboard/src/lib/*.mjs and re-run the script instead.\n',
  transform('cities.js'),
  transform('lc.js'),
  transform('engine.js'),
  transform('format.js'),
  transform('freight.js'),
  transform('capacity.js'),
  transform('columnResize.js'),
  transform('cityOverrides.js'),
  `\n// Public namespaces for the following classic-script app file.\nwindow.INDIA_CITY_TABLE = INDIA_CITY_TABLE;\nwindow.TruckLc = { LC_SOON_DAYS, AGEING_HIGH_DAYS, HTC_CATEGORIES, isAgeingHigh, parseLcDate, formatLc, lcDaysLeft, isLcSoon, htcGroup, buildSoMeta, matchesPlanFilter };\nwindow.TruckEngine = { allocate, buildRows, buildDocks, dockPending, pickUnitsForBand, clusterByProximity, removeUnits, addUnitToSoBreakdown, normalizeCityKey, resolveCity, haversineKm, levenshtein, fuzzyMatchCity, TRUCK_TIERS, DENSITY_T_PER_M3, ODC_MIN_SHARE, CLUB_RADIUS_KM };\nwindow.TruckFormat = { fmt, money, rateText, toCsv, odcDimensionEntries, allDimensionEntries, dimensionText };\nwindow.TruckFreight = { ZONE_STATES, NEAREST_RATE_RADIUS_KM, SOB_STORAGE_KEY, normalizedKey, compactKey, zoneForState, numberValue, round2ui, buildFreightRateModel, odcChargeForDimensions, rtoChargeForDimensions, lookupFreight, shipmentDimensions, totalCostForShipment, analysisRows, parseSobWorkbook, sobStateEntry, computeSobSuggestions };\nwindow.TruckCapacity = { capacity };\nwindow.TruckColumnResize = { installColumnResize };\nwindow.TruckCityOverrides = { loadCityOverrides, saveCityOverride, parseResolveInput };\n`,
].join('\n');

writeFileSync('truck-dashboard-libs.js', out, 'utf8');
console.log('wrote truck-dashboard-libs.js (' + Math.round(out.length / 1024) + ' KB)');

// Quick sanity: the transformed text must parse as a script.
new Function(out);
console.log('syntax OK');
